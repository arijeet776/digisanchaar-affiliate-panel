"""Generates backend/migrations/supabase/001_schema.sql from app/storage/schema.py
(the single source of truth for every table/column the application uses) plus
tools/supabase_functions.sql (the qx_exec storage engine).

    python -m tools.generate_supabase_sql          # rewrite the file
    python -m tools.generate_supabase_sql --check  # exit 1 if the file is stale
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
import importlib.util  # noqa: E402

spec = importlib.util.spec_from_file_location("qx_schema", ROOT / "app/storage/schema.py")
schema = importlib.util.module_from_spec(spec)
spec.loader.exec_module(schema)

OUT = ROOT / "migrations/supabase/001_schema.sql"
PG = {"s": "text", "i": "bigint", "f": "double precision", "b": "boolean", "d": "timestamptz", "m": "numeric(18,2)", "j": "jsonb"}
DATE_FMT = "YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\""
# columns worth an index besides *_id / unique ones
EXTRA_INDEX = {"status", "account_status", "approval_status", "role", "purpose", "transaction_type", "action", "platform", "token_hash"}


def docexpr(t) -> str:
    over = []
    for name, typ in t["columns"]:
        if typ == "d":
            over.append(f"'{name}', to_char(r.\"{name}\" at time zone 'UTC', '{DATE_FMT}')")
        elif typ == "m":
            over.append(f"'{name}', r.\"{name}\"::text")
    ov = f" || jsonb_build_object({', '.join(over)})" if over else ""
    return f"coalesce(r._extra, '{{}}'::jsonb) || (to_jsonb(r) - '_extra' - '_seq'){ov}"


def table_sql(t) -> list[str]:
    name, idf = t["collection"], t["id_field"]
    lines = []
    for col, typ in t["columns"]:
        if col == "_extra":
            lines.append('  "_extra" jsonb')
        elif col == "_id":
            lines.append('  "_id" text primary key default qx_oid()')
        elif col == t.get("autoinc"):
            lines.append(f'  "{col}" bigint generated by default as identity')
        elif col == idf:
            lines.append(f'  "{col}" text primary key')
        else:
            lines.append(f'  "{col}" {PG[typ]}')
    lines.append('  "_seq" bigint generated always as identity')
    out = [f'create table if not exists public."{name}" (\n' + ",\n".join(lines) + "\n);"]
    for i, u in enumerate(t["unique"]):
        if len(u) == 1 and u[0] == idf:
            continue
        cols = ", ".join(f'"{c}"' for c in u)
        out.append(f'create unique index if not exists "ux_{name}_{"_".join(u)}" on public."{name}" ({cols});')
    seen = {tuple(u) for u in t["unique"]}
    for col, _ in t["columns"]:
        if col in ("_extra", "_id", idf) or (col,) in seen:
            continue
        if col.endswith("_id") or col in EXTRA_INDEX or col == t.get("ordered_by") or col in ("expires_at",):
            out.append(f'create index if not exists "ix_{name}_{col}" on public."{name}" ("{col}");')
    return out


def build() -> str:
    tables = [t for t in schema.TABLES if t["collection"] != "_blobs"]  # no 1-cell limit in Postgres
    p = ["-- GENERATED by tools/generate_supabase_sql.py from app/storage/schema.py - do not edit by hand.",
         "-- Run ONCE in the Supabase SQL Editor (safe to re-run: everything is IF NOT EXISTS / OR REPLACE).",
         "-- Security model: RLS is ON for every table with NO policies, and anon/authenticated lose all grants,",
         "-- so the publishable (anon) key can read/write NOTHING. Only the backend's secret/service_role key can.",
         "begin;", "",
         "create or replace function public.qx_oid() returns text language sql volatile as $$ select substr(replace(gen_random_uuid()::text, '-', ''), 1, 24) $$;", "",
         "create table if not exists public.qx_tables (collection text primary key, id_field text not null, append_only boolean not null,",
         "  coltypes jsonb not null, docexpr text not null);", ""]
    for t in tables:
        p += table_sql(t) + [""]
    p.append("-- registry used by qx_exec (column types, identity column, append-only flag, JSON projection)")
    for t in tables:
        types = {c: ty for c, ty in t["columns"]}
        types["_seq"] = "i"
        p.append("insert into public.qx_tables (collection, id_field, append_only, coltypes, docexpr) values ("
                 f"{_q(t['collection'])}, {_q(t['id_field'])}, {str(bool(t['append_only'])).lower()}, {_q(json.dumps(types))}::jsonb, {_q(docexpr(t))}) "
                 "on conflict (collection) do update set id_field = excluded.id_field, append_only = excluded.append_only, coltypes = excluded.coltypes, docexpr = excluded.docexpr;")
    p += ["", (ROOT / "tools/supabase_functions.sql").read_text(), ""]
    p += ["-- the financial ledger is append-only: block UPDATE/DELETE even for privileged roles",
          "create or replace function public.qx_block_mutation() returns trigger language plpgsql as $$ begin raise exception 'financial_ledger is append-only'; end $$;"]
    for t in tables:
        if t["append_only"]:
            n = t["collection"]
            p.append(f'drop trigger if exists "trg_{n}_append_only" on public."{n}";')
            p.append(f'create trigger "trg_{n}_append_only" before update or delete on public."{n}" for each row execute function public.qx_block_mutation();')
    p += ["", "-- lock everything down"]
    for t in tables:
        p.append(f'alter table public."{t["collection"]}" enable row level security;')
    p.append("alter table public.qx_tables enable row level security;")
    p += ["revoke all on all tables in schema public from anon, authenticated;",
          "revoke all on all sequences in schema public from anon, authenticated;",
          "revoke all on all functions in schema public from public, anon, authenticated;",
          "grant all on all tables in schema public to service_role;",
          "grant all on all sequences in schema public to service_role;",
          "grant execute on all functions in schema public to service_role;",
          "alter default privileges in schema public revoke all on tables from anon, authenticated;",
          "alter default privileges in schema public revoke execute on functions from public, anon, authenticated;",
          "notify pgrst, 'reload schema';", "commit;", ""]
    return "\n".join(p)


def _q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT} ({len(text.splitlines())} lines, {sum(1 for t in schema.TABLES if t['collection'] != '_blobs')} tables)")
