"""
Whitelisted macro substitution engine (tracking spec §4/§19).

Rules enforced here, always:
1. Only macros in APPROVED_MACROS are ever substituted — unknown `{...}`
   tokens pass through untouched (they may belong to the destination
   platform's own macro syntax).
2. Macros are string substitutions, never expressions — nothing is
   evaluated, so nothing can execute.
3. Every substituted value is URL-encoded and length-capped.
4. Empty/missing values substitute as empty strings, safely.
"""
import re
from urllib.parse import quote

MAX_MACRO_VALUE_LENGTH = 200

APPROVED_MACROS: frozenset[str] = frozenset(
    {
        "click_id", "digisnr_click_id", "conversion_id", "transaction_id",
        "external_click_id", "agency_click_id", "external_conversion_id",
        "publisher_id", "publisher_code", "campaign_id", "campaign_code",
        "event", "goal", "status", "payout", "revenue", "currency",
        "date_time", "postback_received_at", "event_occurred_at",
        "ip", "country", "country_code", "state", "city",
        "campaign_name", "date",
        "utm_source", "utm_medium", "utm_campaign", "utm_term", "utm_content",
    }
    | {f"p{i}" for i in range(1, 11)}
)

_MACRO_PATTERN = re.compile(r"\{([a-z0-9_]+)\}")


def substitute_macros(template: str, values: dict[str, object]) -> tuple[str, list[str]]:
    """Returns (result, macros_used). Unknown macros are left literally in
    place and excluded from macros_used."""
    used: list[str] = []

    def _replace(match: re.Match) -> str:
        name = match.group(1)
        if name not in APPROVED_MACROS:
            return match.group(0)  # untouched — never evaluate the unknown
        used.append(name)
        value = values.get(name)
        text = "" if value is None else str(value)[:MAX_MACRO_VALUE_LENGTH]
        return quote(text, safe="")

    return _MACRO_PATTERN.sub(_replace, template), used


def macros_present(template: str) -> list[str]:
    return [m for m in _MACRO_PATTERN.findall(template or "")]


